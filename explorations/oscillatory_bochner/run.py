"""Exploration: oscillatory covariance RFs and finite-band spectral diagnostics.

Displays a finite-band spectral diagnostic for a real-part covariance and
generates a separate family of Gaussian fields with nonnegative radial spectra.

For C(r) = exp(-r^2 / 2 Lc^2) with complex Lc = R exp(i theta), the 3D spectral
density has real part:

    Re[S(k)] = (2pi)^(3/2) R^3 exp(-k^2 R^2 cos2theta / 2) cos(3theta - k^2 R^2 sin2theta / 2)

For the REAL PART of C to be a covariance, Re[S(k)] must be nonnegative at
every frequency. For 0 < theta < pi/4 the cosine eventually changes sign:
only theta=0 in the tested range is continuum-valid. Finite k cutoffs and
underflow can hide this failure; the plotted diagnostic is not a validity map.

Separately, oscillatory covariance RFs are generated by shaping the spectral
density as a sum of Gaussians centred at +/- omega = 2pi/lambda in k-space.
These are always valid by construction and interpolate between smooth Gaussian
morphology and quasi-periodic structures.

Run:
    mamba run -n rf_explo python run.py

Outputs (all in results_corrected/, preserving historical results/):
    bochner_map.png         — finite-band spectral minimum in (theta, R) space
    oscillatory_sweep.png   — (Ld, lambda) sweep showing morphology transition

Status: exploratory. Not yet connected to the high-VF Adler story.
Seeds: SEED=7.
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib.cm as cm
import matplotlib.colors as mcolors
import matplotlib.gridspec as mgridspec
import matplotlib.pyplot as plt
import numpy as np

RESULTS = Path(__file__).parent / "results_corrected"

SEED = 7
N = 100
DX = 1.0


# ---------------------------------------------------------------------------
# Bochner validity
# ---------------------------------------------------------------------------

def re_spectral_density(k: np.ndarray, R: float, theta: float) -> np.ndarray:
    """Real-part spectrum, up to its positive R-dependent prefactor."""
    if not np.isfinite(R) or R <= 0 or not np.isfinite(theta) or not 0 <= theta < np.pi/4:
        raise ValueError("Require R>0 and 0<=theta<pi/4 (integrable covariance range)")
    cos2t = np.cos(2.0 * theta)
    sin2t = np.sin(2.0 * theta)
    if cos2t <= 0.0:
        return np.full_like(k, -np.inf)
    amplitude = np.exp(-0.5 * k ** 2 * R ** 2 * cos2t)
    phase = 3.0 * theta - 0.5 * k ** 2 * R ** 2 * sin2t
    return amplitude * np.cos(phase)


def bochner_min(R: float, theta: float, k_max: float, n_k: int = 2000) -> float:
    k = np.linspace(0.0, k_max, n_k)
    return float(re_spectral_density(k, R, theta).min())


def compute_bochner_map(theta_vals: np.ndarray, R_vals: np.ndarray, k_max: float) -> np.ndarray:
    out = np.zeros((len(R_vals), len(theta_vals)))
    for i, R in enumerate(R_vals):
        for j, theta in enumerate(theta_vals):
            out[i, j] = bochner_min(R, theta, k_max)
    return out


# ---------------------------------------------------------------------------
# Oscillatory RF generation
# ---------------------------------------------------------------------------

def spectral_amplitude_oscillatory(n: int, dx: float, L_d: float, lam: float) -> np.ndarray:
    """Nonnegative radial spectrum sampled on a 3D Fourier grid."""
    if n < 4 or any(not np.isfinite(v) or v <= 0 for v in (dx, L_d, lam)):
        raise ValueError("Require n>=4 and positive finite dx, L_d, lambda")
    kx = 2.0 * np.pi * np.fft.fftfreq(n, d=dx)
    ky = 2.0 * np.pi * np.fft.fftfreq(n, d=dx)
    kz = 2.0 * np.pi * np.fft.rfftfreq(n, d=dx)
    KX, KY, KZ = np.meshgrid(kx, ky, kz, indexing="ij")
    k_mag = np.sqrt(KX ** 2 + KY ** 2 + KZ ** 2)
    omega = 2.0 * np.pi / lam
    S = (
        np.exp(-L_d ** 2 * (k_mag - omega) ** 2 / 4.0)
        + np.exp(-L_d ** 2 * (k_mag + omega) ** 2 / 4.0)
    )
    amp = np.sqrt(S)
    if n % 2 == 0:
        # Remove Nyquist planes for a stationary trigonometric interpolant.
        amp[n//2, :, :] = 0
        amp[:, n//2, :] = 0
        amp[:, :, -1] = 0
    return amp


def oscillatory_covariance(r: np.ndarray, L_d: float, lam: float) -> np.ndarray:
    """Normalized 3D inverse Fourier transform of the radial two-Gaussian spectrum.

    This is the untruncated continuum reference; the sampled periodic spectrum
    differs through finite-domain, discretization and Nyquist effects.
    """
    r = np.asarray(r, dtype=float)
    omega = 2*np.pi/lam
    b = .5*(L_d*omega)**2
    return np.exp(-(r/L_d)**2) * (np.cos(omega*r) + b*np.sinc(omega*r/np.pi)) / (1+b)


def generate_oscillatory_rf(n: int, dx: float, L_d: float, lam: float,
                              rng: np.random.Generator) -> np.ndarray:
    amp = spectral_amplitude_oscillatory(n, dx, L_d, lam)
    weights = np.full(n//2+1, 2.)
    weights[0] = 1.
    if n % 2 == 0:
        weights[-1] = 1.
    normalization = np.sqrt(np.sum(amp**2 * weights[None, None, :]) / n**3)
    white = rng.standard_normal((n, n, n))
    return np.fft.irfftn(np.fft.rfftn(white) * amp / normalization,
                        s=(n, n, n), axes=(0, 1, 2))


def empirical_radial_covariance(field: np.ndarray, dx: float,
                                  n_bins: int = 60) -> tuple[np.ndarray, np.ndarray]:
    n = field.shape[0]
    center = n // 2
    F = np.fft.fftn(field)
    acf_3d = np.fft.ifftn(F * np.conj(F)).real / field.size
    acf_3d = np.fft.fftshift(acf_3d)
    ix = np.arange(n) - center
    IX, IY, IZ = np.meshgrid(ix, ix, ix, indexing="ij")
    R_grid = np.sqrt(IX ** 2 + IY ** 2 + IZ ** 2) * dx
    r_max = center * dx
    r_bins = np.linspace(0.0, r_max, n_bins + 1)
    r_centers = 0.5 * (r_bins[:-1] + r_bins[1:])
    C_r = np.zeros(n_bins)
    for b in range(n_bins):
        mask = (R_grid >= r_bins[b]) & (R_grid < r_bins[b + 1])
        if mask.any():
            C_r[b] = acf_3d[mask].mean()
    C_r /= acf_3d[center, center, center]
    return r_centers, C_r


