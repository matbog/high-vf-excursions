"""Exploration: oscillatory covariance RFs and the Bochner validity boundary.

Explores the analogy between the Mandelbrot set (parameter space of the logistic
map) and the space of valid Gaussian covariance parameters.

For C(r) = exp(-r^2 / 2 Lc^2) with complex Lc = R exp(i theta), the 3D spectral
density has real part:

    Re[S(k)] = (2pi)^(3/2) R^3 exp(-k^2 R^2 cos2theta / 2) cos(3theta - k^2 R^2 sin2theta / 2)

Bochner's theorem: C is valid iff Re[S(k)] >= 0 for all k.
The boundary in (theta, R) space is the 'Mandelbrot set' of Gaussian RFs.

Separately, oscillatory covariance RFs are generated by shaping the spectral
density as a sum of Gaussians centred at +/- omega = 2pi/lambda in k-space.
These are always valid by construction and interpolate between smooth Gaussian
morphology and quasi-periodic structures.

Run:
    mamba run -n rf_explo python run.py

Outputs (all in results/):
    bochner_map.png         — Bochner validity map in (theta, R) space
    oscillatory_sweep.png   — (Ld, lambda) sweep showing morphology transition

Status: exploratory. Not yet connected to the high-VF Adler story.
Seeds: SEED=7.
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib.cm as cm
import matplotlib.colors as mcolors
import matplotlib.gridspec as mgridspec
import matplotlib.pyplot as plt
import numpy as np

RESULTS = Path(__file__).parent / "results"
RESULTS.mkdir(exist_ok=True)

SEED = 7
N = 100
DX = 1.0


# ---------------------------------------------------------------------------
# Bochner validity
# ---------------------------------------------------------------------------

def re_spectral_density(k: np.ndarray, R: float, theta: float) -> np.ndarray:
    cos2t = np.cos(2.0 * theta)
    sin2t = np.sin(2.0 * theta)
    if cos2t <= 0.0:
        return np.full_like(k, -np.inf)
    amplitude = np.exp(-0.5 * k ** 2 * R ** 2 * cos2t)
    phase = 3.0 * theta - 0.5 * k ** 2 * R ** 2 * sin2t
    return amplitude * np.cos(phase)


def bochner_min(R: float, theta: float, k_max: float, n_k: int = 2000) -> float:
    k = np.linspace(0.0, k_max, n_k)
    return float(re_spectral_density(k, R, theta).min())


def compute_bochner_map(theta_vals: np.ndarray, R_vals: np.ndarray, k_max: float) -> np.ndarray:
    out = np.zeros((len(R_vals), len(theta_vals)))
    for i, R in enumerate(R_vals):
        for j, theta in enumerate(theta_vals):
            out[i, j] = bochner_min(R, theta, k_max)
    return out


# ---------------------------------------------------------------------------
# Oscillatory RF generation
# ---------------------------------------------------------------------------

def spectral_amplitude_oscillatory(n: int, dx: float, L_d: float, lam: float) -> np.ndarray:
    """S(k) = Gaussian at +omega + Gaussian at -omega, always >= 0."""
    kx = 2.0 * np.pi * np.fft.fftfreq(n, d=dx)
    ky = 2.0 * np.pi * np.fft.fftfreq(n, d=dx)
    kz = 2.0 * np.pi * np.fft.rfftfreq(n, d=dx)
    KX, KY, KZ = np.meshgrid(kx, ky, kz, indexing="ij")
    k_mag = np.sqrt(KX ** 2 + KY ** 2 + KZ ** 2)
    omega = 2.0 * np.pi / lam
    S = (
        np.exp(-L_d ** 2 * (k_mag - omega) ** 2 / 4.0)
        + np.exp(-L_d ** 2 * (k_mag + omega) ** 2 / 4.0)
    )
    return np.sqrt(np.maximum(S, 0.0))


def generate_oscillatory_rf(n: int, dx: float, L_d: float, lam: float,
                              rng: np.random.Generator) -> np.ndarray:
    amp = spectral_amplitude_oscillatory(n, dx, L_d, lam)
    noise = rng.standard_normal((n, n, n // 2 + 1)) + 1j * rng.standard_normal((n, n, n // 2 + 1))
    field = np.fft.irfftn(noise * amp, s=(n, n, n), axes=(0, 1, 2)).real
    field -= field.mean()
    field /= field.std()
    return field


def empirical_radial_covariance(field: np.ndarray, dx: float,
                                  n_bins: int = 60) -> tuple[np.ndarray, np.ndarray]:
    n = field.shape[0]
    center = n // 2
    F = np.fft.fftn(field)
    acf_3d = np.fft.ifftn(F * np.conj(F)).real / field.size
    acf_3d = np.fft.fftshift(acf_3d)
    ix = np.arange(n) - center
    IX, IY, IZ = np.meshgrid(ix, ix, ix, indexing="ij")
    R_grid = np.sqrt(IX ** 2 + IY ** 2 + IZ ** 2) * dx
    r_max = center * dx
    r_bins = np.linspace(0.0, r_max, n_bins + 1)
    r_centers = 0.5 * (r_bins[:-1] + r_bins[1:])
    C_r = np.zeros(n_bins)
    for b in range(n_bins):
        mask = (R_grid >= r_bins[b]) & (R_grid < r_bins[b + 1])
        if mask.any():
            C_r[b] = acf_3d[mask].mean()
    C_r /= C_r[0]
    return r_centers, C_r


# ---------------------------------------------------------------------------
# Figures
# ---------------------------------------------------------------------------

def plot_bochner_map(theta_vals, R_vals, bm, example_fields) -> None:
    n_ex = len(example_fields)
    n_right_cols = 2
    n_right_rows = (n_ex + 1) // 2
    fig = plt.figure(figsize=(6 + 4 * n_right_cols, max(6, 4 * n_right_rows)))
    gs = mgridspec.GridSpec(n_right_rows, 1 + n_right_cols, figure=fig,
                            width_ratios=[2] + [1] * n_right_cols, hspace=0.4, wspace=0.3)
    ax_map = fig.add_subplot(gs[:, 0])
    theta_deg = np.degrees(theta_vals)
    v_abs = float(np.abs(bm[np.isfinite(bm)]).max())
    norm = mcolors.TwoSlopeNorm(vcenter=0.0, vmin=-max(v_abs, 1e-6), vmax=max(v_abs, 1e-6))
    im = ax_map.pcolormesh(theta_deg, R_vals, bm, cmap="RdBu_r", norm=norm, shading="auto")
    ax_map.contour(theta_deg, R_vals, bm, levels=[0.0], colors=["black"], linewidths=2.5)
    ax_map.set_xlabel("θ  (degrees)  — imaginary angle of $L_c = Re^{i\\theta}$")
    ax_map.set_ylabel("R  (correlation length, voxels)")
    ax_map.set_title("Bochner validity map\nBlue = valid  |  Red = invalid  |  Black = boundary")
    ax_map.axvline(30.0, color="gray", ls="--", lw=1.2, alpha=0.7)
    ax_map.text(31.5, R_vals[-1] * 0.95, "θ=30°\n(S(0)=0)", fontsize=8, color="gray", va="top")
    fig.colorbar(im, ax=ax_map, shrink=0.7, label="$\\min_k \\mathrm{Re}[S(k)]$")
    for idx, (L_d, lam, field) in enumerate(example_fields):
        row, col = idx // n_right_cols, idx % n_right_cols
        ax = fig.add_subplot(gs[row, 1 + col])
        mid = field.shape[2] // 2
        ax.imshow((field[:, :, mid] >= 0.5).T, origin="lower", cmap="gray_r",
                  interpolation="nearest")
        ax.set_title(f"$L_d$={L_d:.0f}, λ={lam:.0f}\nλ/Ld={lam/L_d:.1f}", fontsize=9)
        ax.set(xticks=[], yticks=[])
    fig.savefig(RESULTS / "bochner_map.png", dpi=180, bbox_inches="tight")
    plt.close(fig)
    print("  saved bochner_map.png")


def plot_oscillatory_sweep(param_sets, threshold=0.5) -> None:
    n_cols = len(param_sets)
    fig, axes = plt.subplots(3, n_cols, figsize=(3.5 * n_cols, 10), constrained_layout=True)
    rng = np.random.default_rng(SEED)
    for col, (L_d, lam) in enumerate(param_sets):
        field = generate_oscillatory_rf(N, DX, L_d, lam, rng)
        excursion = field >= threshold
        mid = N // 2
        vabs = float(np.percentile(np.abs(field), 99))
        axes[0, col].imshow(field[:, :, mid].T, origin="lower", cmap="RdBu_r",
                             vmin=-vabs, vmax=vabs)
        label = f"λ/Ld={lam/L_d:.1f}" if lam < 5 * L_d else "λ >> Ld"
        axes[0, col].set_title(f"Ld={L_d:.0f}, λ={lam:.0f}\n{label}", fontsize=9)
        axes[0, col].set(xticks=[], yticks=[])
        axes[1, col].imshow(excursion[:, :, mid].T, origin="lower", cmap="gray_r",
                             interpolation="nearest")
        axes[1, col].set_title(f"VF={excursion.mean():.2f}", fontsize=9)
        axes[1, col].set(xticks=[], yticks=[])
        r_vals, C_r = empirical_radial_covariance(field, DX, n_bins=50)
        axes[2, col].plot(r_vals, C_r, "b-", lw=1.5, label="empirical")
        r_th = np.linspace(1e-9, r_vals[-1], 300)
        C_th = np.sinc(2.0 * r_th / lam) * np.exp(-(r_th / L_d) ** 2)
        axes[2, col].plot(r_th, C_th, "r--", lw=1, alpha=0.7, label="target")
        axes[2, col].axhline(0, color="gray", lw=0.7, ls=":")
        axes[2, col].set_xlim(0, min(r_vals[-1], 5 * L_d))
        axes[2, col].set_ylim(-1.1, 1.1)
        axes[2, col].set_xlabel("r (voxels)", fontsize=8)
        if col == 0:
            axes[2, col].set_ylabel("C(r)", fontsize=9)
            axes[2, col].legend(fontsize=7)
        axes[2, col].tick_params(labelsize=7)
        axes[2, col].grid(alpha=0.3)
    axes[0, 0].set_ylabel("Field (z-slice)", fontsize=9)
    axes[1, 0].set_ylabel("Excursion (u=0.5σ)", fontsize=9)
    fig.suptitle("Oscillatory covariance RF: morphology from smooth to quasi-periodic", fontsize=11)
    fig.savefig(RESULTS / "oscillatory_sweep.png", dpi=180, bbox_inches="tight")
    plt.close(fig)
    print("  saved oscillatory_sweep.png")


def main() -> None:
    k_max = np.pi / DX

    print("Computing Bochner validity map (~10 seconds)...")
    theta_vals = np.linspace(0.0, np.pi / 4.0, 120)
    R_vals = np.linspace(2.0, 20.0, 100)
    bm = compute_bochner_map(theta_vals, R_vals, k_max)

    rng = np.random.default_rng(SEED)
    example_params = [(10.0, 200.0), (10.0, 20.0), (10.0, 10.0), (10.0, 5.0)]
    example_fields = [
        (L_d, lam, generate_oscillatory_rf(N, DX, L_d, lam, rng))
        for L_d, lam in example_params
    ]
    plot_bochner_map(theta_vals, R_vals, bm, example_fields)

    print("Generating oscillatory morphology sweep...")
    sweep_params = [(8.0, 500.0), (8.0, 40.0), (8.0, 16.0), (8.0, 8.0), (8.0, 4.0)]
    plot_oscillatory_sweep(sweep_params, threshold=0.5)

    print("Done. Results in explorations/oscillatory_bochner/results/")


if __name__ == "__main__":
    main()
